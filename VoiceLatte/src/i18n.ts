const messages = { ja, en };

export type Translator = (key: MessageKey, values?: Record<string, string | number>) => string;

export function resolveUiLanguage(preference: UiLanguagePreference, systemLocale = navigator.language): UiLanguage {
  if (preference !== "system") return preference;
  return systemLocale.toLowerCase().startsWith("ja") ? "ja" : "en";
}

export function resolveSpeechLocale(preference: string, systemLocales = navigator.languages) {
  if (preference !== "system") return preference;
  const locale = systemLocales.find(Boolean);
  return locale || "en-US";
}

export function createTranslator(language: UiLanguage): Translator {
  return (key, values) => {
    const template = messages[language][key] ?? ja[key];
    return template.replace(/\{(\w+)\}/g, (_, name: string) => String(values?.[name] ?? `{${name}}`));
  };
}

export function defaultPrompts(language: UiLanguage) {
  return language === "ja"
    ? {
        defaultPrompt: "フィラーを削除し、句読点・数字・金額・日付・単位だけを自然な表記に整えてください。言い換えや要約はしないでください。",
        chatPrompt: "会話らしい自然さを保ち、簡潔に整えてください。",
        codePrompt: "技術用語、識別子、コマンド、パスを変更しないでください。",
      }
    : {
        defaultPrompt: "Remove filler words and only format punctuation, numbers, money, dates, and units naturally. Do not paraphrase or summarize.",
        chatPrompt: "Keep the conversational tone natural and concise.",
        codePrompt: "Do not change technical terms, identifiers, commands, or paths.",
      };
}

export function localizeBridgeMessage(message: string, language: UiLanguage, t: Translator) {
  if (language === "ja" || !/[ぁ-んァ-ヶ一-龯]/u.test(message)) return message;
  if (message.includes("応答がありません")) return t("error.bridgeTimeout");
  if (message.includes("ブリッジが終了")) return t("error.bridgeClosed");
  return t("error.speechUnavailable");
}
