export function localizeBridgeMessage(message: string, language: UiLanguage, t: Translator) {
  const cloudErrors: Record<string, MessageKey> = {
    "cloud.capture_prepare": "error.cloudCapture",
    "cloud.capture_discard": "error.cloudCapture",
    "cloud.capture_read": "error.cloudCapture",
    "cloud.capture_missing": "error.cloudCapture",
    "cloud.key_empty": "error.cloudKeyEmpty",
    "cloud.key_save": "error.cloudKeySave",
    "cloud.key_status": "error.cloudKeyStatus",
    "cloud.key_delete": "error.cloudKeyDelete",
    "cloud.key_missing": "error.cloudKeyMissing",
    "cloud.key_read": "error.cloudKeyRead",
    "cloud.key_denied": "error.cloudKeyDenied",
    "cloud.credential_store": "error.cloudKeyRead",
    "cloud.audio_too_long": "error.cloudAudioTooLong",
    "cloud.audio_empty": "error.cloudAudioEmpty",
    "cloud.audio_format": "error.cloudCapture",
    "cloud.connect": "error.cloudCapture",
    "cloud.groq_connect": "error.groqConnect",
    "cloud.groq_key": "error.groqKey",
    "cloud.gemini_connect": "error.geminiConnect",
    "cloud.gemini_key": "error.geminiKey",
    "cloud.response": "error.cloudResponse",
    "cloud.no_speech": "error.cloudNoSpeech",
    "cloud.stream_stopped": "error.cloudStreamStopped",
    "cloud.invalid_provider": "error.cloudCapture",
  };
  const [code, status = ""] = message.split(":", 2);
  if (code === "cloud.groq_failed") return t("error.groqFailed", { status });
  if (code === "cloud.gemini_failed") return t("error.geminiFailed", { status });
  if (cloudErrors[code]) return t(cloudErrors[code]);
  if (language === "ja" || !/[ぁ-んァ-ヶ一-龯]/u.test(message)) return message;
  if (message.includes("応答がありません")) return t("error.bridgeTimeout");
  if (message.includes("ブリッジが終了")) return t("error.bridgeClosed");
  return t("error.speechUnavailable");
}
